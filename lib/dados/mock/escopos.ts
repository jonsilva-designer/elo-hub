// depois do término da vigência do contrato dela, para o aviso da RN-21 aparecer em qualquer dia.

export type EscopoFicticio = Escopo & { conclusaoPrevistaEmDias?: number }

const ORDEM: EtapaJornada[] = ['Diagnosticar', 'Estruturar', 'Implementar', 'Monitorar', 'Evoluir']

/** As 5 etapas na ordem oficial. As que não aparecem ficam Não iniciadas, sem responsável nem datas. */
function jornada(mexidas: Partial<Record<EtapaJornada, Partial<Omit<LinhaEtapa, 'etapa'>>>> = {}): LinhaEtapa[] {
  return ORDEM.map((etapa) => ({
    etapa,
    status: 'Não iniciada',
    responsavelId: null,
    inicio: null,
    conclusao: null,
    observacoes: '',
    ...mexidas[etapa],
  }))
}

